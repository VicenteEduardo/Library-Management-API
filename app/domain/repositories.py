"""O contrato com a base de dados: o que precisamos de guardar e ir buscar.

O domínio só diz "preciso disto"; quem cumpre o contrato (SQLite, memória, etc.)
fica noutro ficheiro. É assim que evitamos prender as regras a uma tecnologia."""
from abc import ABC, abstractmethod
from typing import List, Optional

from app.domain.entities import Book, Loan, Member


class BookRepository(ABC):
    @abstractmethod
    def add(self, book: Book) -> Book: ...
    @abstractmethod
    def get_by_id(self, book_id: int) -> Optional[Book]: ...
    @abstractmethod
    def get_by_isbn(self, isbn: str) -> Optional[Book]: ...
    @abstractmethod
    def list(self, skip: int = 0, limit: int = 100) -> List[Book]: ...
    @abstractmethod
    def update(self, book: Book) -> Book: ...
    @abstractmethod
    def delete(self, book_id: int) -> None: ...


class MemberRepository(ABC):
    @abstractmethod
    def add(self, member: Member) -> Member: ...
    @abstractmethod
    def get_by_id(self, member_id: int) -> Optional[Member]: ...
    @abstractmethod
    def get_by_email(self, email: str) -> Optional[Member]: ...
    @abstractmethod
    def list(self, skip: int = 0, limit: int = 100) -> List[Member]: ...
    @abstractmethod
    def update(self, member: Member) -> Member: ...
    @abstractmethod
    def delete(self, member_id: int) -> None: ...


class LoanRepository(ABC):
    @abstractmethod
    def add(self, loan: Loan) -> Loan: ...
    @abstractmethod
    def get_by_id(self, loan_id: int) -> Optional[Loan]: ...
    @abstractmethod
    def list(self, skip: int = 0, limit: int = 100) -> List[Loan]: ...
    @abstractmethod
    def list_active_by_member(self, member_id: int) -> List[Loan]: ...
    @abstractmethod
    def find_active(self, book_id: int, member_id: int) -> Optional[Loan]: ...
    @abstractmethod
    def update(self, loan: Loan) -> Loan: ...
